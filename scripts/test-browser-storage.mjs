import 'fake-indexeddb/auto';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import ts from 'typescript';
const source = await readFile(new URL('../lib/browser-storage.ts', import.meta.url), 'utf8');
const js = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } }).outputText;
const { listPhotos, savePhoto, deletePhoto, releasePhotoUrls } = await import('data:text/javascript;base64,' + Buffer.from(js).toString('base64'));
const blob = new Blob([new Uint8Array([255,216,255,0,1,2])], {type: 'image/jpeg'});
const draft = {id:'new',location:' Kitchen ',notes:'Top shelf',items:[{id:'item-1',label:' Mug ',box:null,source:'manual'}],width:100,height:100,createdAt:'',imageUrl:'',blob};
assert.deepEqual(await listPhotos(), []);
const first = await savePhoto(draft);
assert.equal(first.location, 'Kitchen');
assert.equal(first.items[0].label, 'Mug');
assert.notEqual(first.id, 'new');
assert.equal((await listPhotos()).length, 1);
assert.deepEqual(new Uint8Array(await (await fetch(first.imageUrl)).arrayBuffer()), new Uint8Array(await blob.arrayBuffer()));
const updated = await savePhoto({...first, location:'Hall closet', notes:'Second shelf'});
assert.equal(updated.id, first.id);
assert.equal(updated.createdAt, first.createdAt);
releasePhotoUrls(); // Simulate reconstructing display URLs after a reload.
const reloaded = await listPhotos();
assert.equal(reloaded[0].location, 'Hall closet');
assert.equal(reloaded[0].notes, 'Second shelf');
assert.notEqual(reloaded[0].imageUrl, first.imageUrl);
assert.deepEqual(new Uint8Array(await (await fetch(reloaded[0].imageUrl)).arrayBuffer()), new Uint8Array(await blob.arrayBuffer()));
await assert.rejects(savePhoto({...draft,location:' '}), /location/);
await assert.rejects(savePhoto({...draft,items:Array(61).fill(draft.items[0])}), /60/);
await assert.rejects(savePhoto({...draft,sample:true}), /own photo/);
// An aborted transaction must reject and leave the previously saved record intact.
const originalPut = IDBObjectStore.prototype.put;
IDBObjectStore.prototype.put = function(...args) { const result = originalPut.apply(this,args); this.transaction.abort(); return result; };
await assert.rejects(savePhoto({...updated,location:'Must not persist'}));
IDBObjectStore.prototype.put = originalPut;
assert.equal((await listPhotos())[0].location, 'Hall closet');
await deletePhoto(first.id);
assert.deepEqual(await listPhotos(), []);
await assert.rejects(savePhoto(first), /no longer saved/);
releasePhotoUrls();
console.log('Passed browser storage create, reload, image integrity, edit, delete, validation, and aborted-write checks.');
